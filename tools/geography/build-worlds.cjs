// Rebuild browser data from the editable JSON worlds; zero-build file:// support.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
const context = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(path.join(root, 'assets/js/geography.js'), 'utf8'), context);
const worlds = {};
const images = {};
for (const file of fs.readdirSync(path.join(root, 'worlds')).filter(n => n.endsWith('.json'))) {
    const data = JSON.parse(fs.readFileSync(path.join(root, 'worlds', file), 'utf8'));
    context.window.RPHubGeography.validate(data);
    if (data.calibration?.autoScale) {
        if (data.edges.some(e => e.meters !== undefined)) throw new Error('自动图示时间标定不可与实测边混合；请改用明确长度');
        const units = context.window.RPHubGeography.path({ ...data, metersPerUnit: 1 }, data.calibration.anchorFrom, data.calibration.anchorTo, 'walk');
        if (!units || units.length <= 0 || !Number.isFinite(data.calibration.walkMinutes) || data.calibration.walkMinutes <= 0 || !Number.isFinite(data.calibration.assumedWalkMetersPerMinute) || data.calibration.assumedWalkMetersPerMinute <= 0) throw new Error('标定路线不可达或时间/步速不合法');
        data.metersPerUnit = data.calibration.walkMinutes * data.calibration.assumedWalkMetersPerMinute / units.length;
        fs.writeFileSync(path.join(root, 'worlds', file), JSON.stringify(data, null, 2) + '\n');
    }
    if (worlds[data.id]) throw new Error('重复 worldId: ' + data.id);
    worlds[data.id] = data;
    if (data.image) {
        const imageFile = path.resolve(root, data.image);
        if (!imageFile.startsWith(root + path.sep)) throw new Error('底图路径超出工程');
        const mime = { '.png': 'png', '.jpeg': 'jpeg', '.jpg': 'jpeg', '.webp': 'webp' }[path.extname(imageFile).toLowerCase()];
        if (!mime) throw new Error('底图仅支持PNG/JPEG/WebP');
        images[data.id] = 'data:image/' + mime + ';base64,' + fs.readFileSync(imageFile).toString('base64');
    }
}
fs.writeFileSync(path.join(root, 'assets/js/world-data.js'), '// Generated by tools/geography/build-worlds.cjs; edit worlds/*.json.\nwindow.RPHubWorlds = ' + JSON.stringify(worlds, null, 2) + ';\n');
fs.writeFileSync(path.join(root, 'assets/js/world-images.js'), '// Generated original raster assets, lazily loaded by map management; never sent to models.\nwindow.RPHubWorldImages = ' + JSON.stringify(images) + ';\n');
console.log('worlds:', Object.keys(worlds).join(', '));
